from typing import Protocol, Tuple
from karum.domain.entity import Wallet


class WalletRepository(Protocol):
    async def create(self, wallet: Wallet) -> Wallet: ...
    async def get(self, id: int) -> Wallet: ...
    async def get_all(self, account_id: int) -> Tuple[Wallet, ...]: ...
    async def get_all_by_provider_id(self, provider_id: str) -> Tuple[Wallet, ...]: ...
    async def update(self, id: int, data: dict = {}, **kwargs) -> None: ...
